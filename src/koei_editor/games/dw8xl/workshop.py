"""Read-only character and weapon planning data for DW8 XL Complete Edition PC.

This provider projects the existing validated parser and progression dashboard.
It contains no writer and does not derive damage, power or progression values.
"""
from dataclasses import dataclass
from types import MappingProxyType
from typing import Mapping

from koei_editor.games.dw3.models import SaveError
from koei_editor.games.dw8xl.dashboard import dashboard
from koei_editor.shared import verified_editor
from koei_editor.shared.verified_editor import CompatibilityField
from koei_editor.games.dw3.game_content import DW8_ATTRIBUTE_NAMES


GAME_ID = 'dw8xl'
PLATFORM_ID = 'windows_pc'
EVIDENCE = (
    'docs/PROGRESSION_DASHBOARDS.md: DW8 XL PC mapped opened-save stats and equipment.',
    'docs/DW8_COMPATIBILITY.md: native PC aptitude order, 25 stored units per star, '
    'existing weapon choices and mapped attribute behavior.',
    'docs/GAME_SPECIFIC_EXPANSION.md: qualified ranked-attribute replacement and rank checks.',
)


@dataclass(frozen=True)
class WorkshopField:
    """One field the selected game's validated editor already maps.

    ``character_id`` is a stable logical record key for portable build plans;
    it does not claim roster names, unlock state or ownership.
    """

    field_id: str
    label: str
    category: str
    character_id: str
    current_value: object
    choices: tuple[tuple[object, str], ...] = ()
    evidence: str = ''


@dataclass(frozen=True)
class WorkshopProjection:
    game_id: str
    platform_id: str
    title: str
    dashboard: object
    fields: Mapping[str, WorkshopField]
    evidence: tuple[str, ...]


def _character_id(field):
    if field.group in ('Officers', 'Weapon compatibility', 'Weapon order'):
        return f'officer:{field.slot - 1}'
    if field.group in ('Weapon affinity', 'Weapon attributes', 'Weapon attribute identities'):
        return f'weapon:{field.slot - 1}'
    return 'save'


def _field_evidence(field):
    if field.group == 'Weapon compatibility':
        return (EVIDENCE[1] + ' Four-star display is reused from the existing dashboard; '
                'unusual raw units remain uncalculated.')
    if field.group in ('Weapon affinity', 'Weapon attributes', 'Weapon attribute identities', 'Weapon order'):
        return EVIDENCE[1]
    return EVIDENCE[0] + ' Values are stored parser fields; no gameplay formula is applied.'


def workshop_projection(document, backend=verified_editor):
    """Return mapped fields, native choices and the game's existing dashboard.

    The projection is frozen, carries no source path/hash, and has no stage or
    serialize method. Choices are generated by the same parser hook used by the
    editor, so only currently qualified native selections appear here.
    """
    backend.validate_document(document)
    if document.format.id != GAME_ID:
        raise SaveError('The DW8 XL PC workshop requires its qualified PC save document.')

    projected = {}
    choice_groups = {
        'Weapon compatibility', 'Weapon order', 'Weapon affinity',
        'Weapon attribute identities',
    }
    for field in backend.fields_for(document):
        choices = (tuple(backend.field_options(document, field.id))
                   if field.group in choice_groups else ())
        value = field.value(document.payload)
        projected[field.id] = WorkshopField(
            field_id=field.id,
            label=field.label,
            category=field.group,
            character_id=_character_id(field),
            current_value=value,
            choices=choices,
            evidence=_field_evidence(field),
        )

    view = dashboard(backend, document)
    return WorkshopProjection(
        GAME_ID, PLATFORM_ID, view.title, view,
        MappingProxyType(projected), EVIDENCE,
    )


def compare_weapon_records(document, left_slot, right_slot, backend=verified_editor):
    """Return the existing read-only weapon cards for side-by-side comparison.

    The UI can compare the stored attack, affinity and ranked attributes. This
    deliberately does not calculate combat damage or elemental effectiveness.
    """
    backend.validate_document(document)
    if document.format.id != GAME_ID:
        raise SaveError('The DW8 XL PC workshop requires its qualified PC save document.')
    if type(left_slot) is not int or type(right_slot) is not int:
        raise SaveError('Choose two mapped DW8 XL weapon record slots.')

    records = {row['slot']: row for row in backend.weapons(document)}
    if left_slot not in records or right_slot not in records:
        raise SaveError('Choose two populated DW8 XL weapon records from the opened copy.')
    cards = {card.id: card
             for section in dashboard(backend, document).sections
             if section.id == 'equipment'
             for card in section.cards}
    left, right = cards.get(f'weapon_{left_slot}'), cards.get(f'weapon_{right_slot}')
    if left is None or right is None:
        raise SaveError('The mapped DW8 XL weapon dashboard is unavailable.')
    return left, right


def weapon_record_options(document, backend=verified_editor):
    """Return qualified populated record slots for the graphical comparison."""
    backend.validate_document(document)
    if document.format.id != GAME_ID:
        raise SaveError('The DW8 XL PC workshop requires its qualified PC save document.')
    cards = {card.id: card
             for section in dashboard(backend, document).sections
             if section.id == 'equipment'
             for card in section.cards}
    return tuple((row['slot'], cards[f"weapon_{row['slot']}"].title)
                 for row in backend.weapons(document)
                 if f"weapon_{row['slot']}" in cards)


def attribute_label(identity):
    """Return a verified localized name or an explicit unmapped ID label."""
    if type(identity) is not int or identity < 0:
        raise SaveError('Choose a non-negative native DW8 XL attribute ID.')
    return DW8_ATTRIBUTE_NAMES.get(identity, f'Attribute ID {identity}')


def is_mapped_field(document, field_id, backend=verified_editor):
    """Check a plan field against this exact opened document's field map."""
    backend.validate_document(document)
    if document.format.id != GAME_ID or type(field_id) is not str:
        return False
    return field_id in backend.field_map(document)
