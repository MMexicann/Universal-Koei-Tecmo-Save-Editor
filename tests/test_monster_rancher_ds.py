    def test_replicas_unknowns_are_not_copied_or_active_counter_guessed(self):
        raw = bytearray(fixture())
        raw[p.ENTRY_BASES[1]] = 219
        raw[p.ENTRY_BASES[1] + 8000] = 117
        raw = reseal(raw)
        self.assertNotEqual(raw[34:34 + p.ENTRY_SIZE], raw[34 + p.ENTRY_SIZE:34 + p.ENTRY_SIZE * 2])
        self.surgical(raw, {'gold': 5000, 'monster_0_stat_1': 900})
        differs = modified_monster(raw, slot=1, stats=(20, 30, 40, 50, 60, 70), replicas=(1,))
        mapping = p.field_map(p.decode(differs))
        self.assertNotIn('monster_1_name', mapping)
        self.assertNotIn('monster_1_stat_0', mapping)
        self.assertIn('monster_0_stat_0', mapping)
        self.surgical(differs, {'monster_0_stat_0': 999})
        other = bytearray(raw)
        other[p.ENTRY_BASES[1] + 27] = ord('X')
        self.assertEqual(p.fields_for(p.decode(reseal(other))), ())

    def test_dead_empty_noncanonical_and_unusual_record_guard(self):
        raw = fixture()
        for changed in (modified_monster(raw, lifespan=0),
                        modified_monster(raw, name=b'\xff' + b'\0' * 11),
                        modified_monster(raw, name=b'A\0trailing!!'),
                        modified_monster(raw, stats=(65535, 1, 1, 1, 1, 1))):
            doc = p.decode(changed)
            self.assertNotIn('monster_0_stat_0', p.field_map(doc))
            self.assertNotIn('monster_0_lifespan', p.field_map(doc))
            self.assertIn('monster_1_stat_0', p.field_map(doc))
            self.assertEqual(p.serialize(doc, {}), changed)
        with self.assertRaises(SaveError):
            p.stage(p.decode(raw), {}, 'monster_2_stat_0', 999)
        unusual_life = modified_monster(raw, lifespan=65535)
        self.assertNotIn('monster_0_lifespan', p.field_map(p.decode(unusual_life)))
        self.surgical(unusual_life, {'monster_0_stat_0': 999})
        unknown = bytearray(raw)
        for base in p.ENTRY_BASES:
            struct.pack_into('<H', unknown, base + p.MONSTER_BASE + 18, 0xFFFE)
        unknown = reseal(unknown)
        doc = p.decode(unknown)
        self.assertNotIn('monster_0_name', p.field_map(doc))
        self.assertNotIn('monster_0_stat_0', p.field_map(doc))
        self.surgical(unknown, {'gold': 5000})

    def test_stats_caps_budget_and_max_preserve_overdrive_and_unusual_totals(self):
        raw = fixture()
        doc = p.decode(raw)
        pending = p.maximums(doc, {})
        reopened = p.decode(p.serialize(doc, pending))
        for slot in (0, 1):
            self.assertEqual(p._monster(reopened.raw, 0, slot)[-1], (999,) * 6)
            self.assertEqual(p._monster(reopened.raw, 0, slot)[4], 9999)
        self.assertNotIn('gold', pending)
        overdrive = modified_monster(raw, stats=(1500, 1500, 1500, 1494, 0, 0))
        doc = p.decode(overdrive)
        self.assertEqual(p.stage(doc, {}, 'monster_0_stat_0', 1500), {})
        self.assertEqual(p._monster(p.serialize(doc, p.maximums(doc, {})), 0, 0)[-1],
                         (1500, 1500, 1500, 1494, 0, 0))
        with self.assertRaises(SaveError):
            p.stage(doc, {}, 'monster_0_stat_4', 1)
        pending = p.stage(doc, {}, 'monster_0_stat_0', 900)
        pending = p.stage(doc, pending, 'monster_0_stat_4', 600)
        self.assertEqual(sum(p._monster(p.serialize(doc, pending), 0, 0)[-1]), 5994)
        with self.assertRaises(SaveError):
            p.stage(doc, pending, 'monster_0_stat_4', 601)
        unusual = modified_monster(raw, stats=(1500,) * 6)
        self.assertEqual(p.serialize(p.decode(unusual), {}), unusual)
        self.surgical(unusual, {'monster_0_stat_0': 999})

