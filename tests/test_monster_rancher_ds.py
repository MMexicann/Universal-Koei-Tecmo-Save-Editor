    def test_storage_backups_source_changed_after_backup_and_restore_bounded_validated(self):
        raw = fixture(65536)
        with tempfile.TemporaryDirectory() as directory:
            folder = Path(directory)
            source = folder / 'copy.sav'
            source.write_bytes(raw)
            doc = p.read_save(source)
            adapter = BoundScalarAdapter(p.GAME_ID, '.sav', p)
            saved = adapter.save_as(doc, {'gold': 5000}, folder / 'edited.sav')
            self.assertEqual(p.field_map(saved)['gold'].value(saved.raw), 5000)
            snapshot = p.backup(doc)
            self.assertEqual(json.loads(snapshot.with_suffix('.json').read_bytes())['game_id'], p.GAME_ID)
            self.assertEqual(p.restore(snapshot, folder / 'restored.sav').read_bytes(), raw)
            for dest in (source, saved.source):
                with self.assertRaises(FileExistsError):
                    p.save_as(doc, {}, dest)
            existing_backup = p.backup
            def mutate_after_backup(document):
                result = existing_backup(document)
                source.write_bytes(raw[:-1] + bytes([raw[-1] ^ 1]))
                return result
            with patch.object(p, 'backup', side_effect=mutate_after_backup):
                with self.assertRaises(SaveError):
                    p.save_as(doc, {}, folder / 'raced.sav')
            self.assertFalse((folder / 'raced.sav').exists())
            with self.assertRaises(SaveError):
                p.backup(doc)
            metadata = json.loads(snapshot.with_suffix('.json').read_bytes())
            metadata['game_id'] = 'different_game'
            snapshot.with_suffix('.json').write_text(json.dumps(metadata))
            with self.assertRaises(SaveError):
                p.restore(snapshot, folder / 'wrong-game.sav')
            self.assertFalse((folder / 'wrong-game.sav').exists())

