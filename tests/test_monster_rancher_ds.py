    def test_genuine_five_native_copies_noop_full_crcs_surgical_features_storage(self):
        paths = native_paths()
        if not paths:
            self.skipTest('Private freely shared native MRDS .sav copies not provided.')
        unique, edits, physical_sizes, full_name_width = set(), 0, set(), False
        for original in paths:
            raw = original.read_bytes()
            digest = hashlib.sha256(raw).digest()
            if digest in unique:
                continue
            unique.add(digest)
            physical_sizes.add(len(raw))
            with self.subTest(sample=original.name):
                doc = p.decode(raw)
                self.assertEqual(p.serialize(doc, {}), raw)
                mapping = p.field_map(doc)
                if 'monster_0_name' in mapping:
                    field = mapping['monster_0_name']
                    if len(field.value(raw)) == 12 and b'\0' not in raw[field.offset:field.offset + 12]:
                        full_name_width = True
                if not mapping:
                    continue  # Genuine initialized empty ranch: no fabricated ownership.
                changes = {'gold': max(0, mapping['gold'].value(raw) - 100),
                           'player_name': 'Test Breeder', 'ranch_name': 'Test Ranch',
                           'monster_0_name': 'Test Monster', 'monster_0_stat_0': 999,
                           'monster_0_lifespan': 9999}
                self.surgical(raw, changes)
                with tempfile.TemporaryDirectory() as directory:
                    folder = Path(directory)
                    source = folder / 'copy.sav'
                    source.write_bytes(raw)
                    copied = p.read_save(source)
                    saved = p.save_as(copied, changes, folder / 'edited.sav')
                    self.assertNotEqual(saved.raw, raw)
                    snapshot = p.backup(copied)
                    self.assertEqual(p.restore(snapshot, folder / 'restored.sav').read_bytes(), raw)
                    self.assertEqual(source.read_bytes(), raw)
                self.assertEqual(original.read_bytes(), raw)
                edits += 1
        self.assertGreaterEqual(len(unique), 5)
        self.assertEqual(physical_sizes, {32768,65536})
        self.assertGreaterEqual(edits, 4)
        self.assertTrue(full_name_width, 'Native occupied monster names prove all twelve bytes can be used without NUL.')

    def test_actual_tk_native_when_available_find_names_bulk_undo_review_inspect_save_restore(self):
        try:
            import tkinter as tk
            root = tk.Tk()
        except Exception as error:
            self.skipTest('Tk display unavailable: ' + type(error).__name__)
        self.addCleanup(root.destroy)
        from koei_editor.games.monster_rancher_ds.editor import Editor
        raws = [path.read_bytes() for path in native_paths()]
        raw = next((raw for raw in raws if p.fields_for(p.decode(raw))), fixture())
        with tempfile.TemporaryDirectory() as directory:
            folder = Path(directory)
            source = folder / 'copy.sav'
            source.write_bytes(raw)
            editor = Editor(root, parent=root)
            with patch('koei_editor.shared.verified_gui.filedialog.askopenfilename', return_value=str(source)):
                editor.open()
            root.update()
            self.assertEqual(len(editor.fields.get_children()), len(p.fields_for(editor.document)))
            editor.search.set('lifespan')
            root.update()
            self.assertIn('monster_0_lifespan', editor.fields.get_children())
            editor.search.set('')
            editor.stage_values({'monster_0_stat_0': 999, 'player_name':'Test Breeder'})
            self.assertEqual(len(p.review(editor.document, editor.changes)), 2)
            editor.undo()
            self.assertEqual(editor.changes, {})
            editor.stage_values({'monster_0_stat_0': 999, 'player_name':'Test Breeder'})
            editor.review()
            editor.show_inspector()
            root.update()
            for child in list(root.winfo_children()):
                if isinstance(child, tk.Toplevel):
                    child.destroy()
            destination = folder / 'edited.sav'
            with patch('koei_editor.shared.verified_gui.filedialog.asksaveasfilename', return_value=str(destination)):
                editor.save_as()
            saved = p.read_save(destination)
            self.assertEqual(p.field_map(saved)['monster_0_stat_0'].value(saved.raw), 999)
            self.assertEqual(p.field_map(saved)['player_name'].value(saved.raw), 'Test Breeder')
            snapshots = list((folder / 'UniversalEditorBackups').glob('*.sav'))
            self.assertTrue(snapshots)
            self.assertEqual(p.restore(snapshots[0], folder / 'restored.sav').read_bytes(), raw)
            self.assertEqual(source.read_bytes(), raw)


