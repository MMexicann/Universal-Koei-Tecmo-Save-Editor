def reseal(raw):
    result = bytearray(raw)
    for base in p.ENTRY_BASES:
        struct.pack_into('<I', result, base + p.HEADER_CRC, zlib.crc32(result[base:base + p.HEADER_CRC]))
        struct.pack_into('<I', result, base + p.BODY_CRC, zlib.crc32(result[base:base + p.BODY_CRC]))
    return bytes(result)


def fixture(size=32768):
    """Generated bytes from published field facts; not a genuine player save."""
    raw = bytearray((i * 17 + 7) % 256 for i in range(size))
    raw[:34] = p.SIGNATURE
    entry = bytearray(p.ENTRY_SIZE)
    entry[10:23] = b'Test Ranch' + bytes(3)
    entry[27:40] = b'Test Player' + bytes(2)
    struct.pack_into('<I', entry, 352, 12090)
    struct.pack_into('<50H', entry, 356, 3, 6, 13, 14, *([0xFFFF] * 46))
    for slot in range(31):
        struct.pack_into('<H', entry, p.MONSTER_BASE + slot * p.MONSTER_SIZE + 18, 0xFFFF)
    for slot, name, species in ((0, b'Test current', 3), (1, b'Test frozen', 56)):
        offset = p.MONSTER_BASE + slot * p.MONSTER_SIZE
        entry[offset:offset + 12] = name + bytes(12 - len(name))
        struct.pack_into('<H', entry, offset + 18, species)
        struct.pack_into('<HH', entry, offset + 30, 2, 1914)
        struct.pack_into('<6H', entry, offset + 40, 174, 130, 130, 76, 91, 98)
    for base in p.ENTRY_BASES:
        raw[base:base + p.ENTRY_SIZE] = entry
    return reseal(raw)


def modified_monster(raw, slot=0, stats=None, lifespan=None, name=None, replicas=(0, 1)):
    out = bytearray(raw)
    for replica in replicas:
        base = p.ENTRY_BASES[replica] + p.MONSTER_BASE + slot * p.MONSTER_SIZE
        if stats is not None:
            struct.pack_into('<6H', out, base + 40, *stats)
        if lifespan is not None:
            struct.pack_into('<H', out, base + 32, lifespan)
        if name is not None:
            out[base:base + 12] = name
    return reseal(out)


def native_paths():
    return [path for item in os.environ.get('MRDS_SAVE_COPIES', '').split(os.pathsep) if item
            for path in ([Path(item)] if Path(item).is_file() else Path(item).rglob('*.sav'))]


class MonsterRancherDsTests(unittest.TestCase):
    def surgical(self, raw, changes):
        document = p.decode(raw)
        mapping = p.field_map(document)
        allowed = {i for key in changes for delta in (0, p.ENTRY_SIZE)
                   for i in range(mapping[key].offset + delta, mapping[key].offset + delta + mapping[key].size)}
        allowed |= {base + offset + i for base in p.ENTRY_BASES
                    for offset in (p.HEADER_CRC, p.BODY_CRC) for i in range(4)}
        output = p.serialize(document, changes)
        touched = {i for i, (a, b) in enumerate(zip(raw, output)) if a != b}
        self.assertTrue(touched)
        self.assertLessEqual(touched, allowed)
        self.assertEqual(len(raw), len(output))
        self.assertEqual(output[34 + 2 * p.ENTRY_SIZE:], raw[34 + 2 * p.ENTRY_SIZE:])
        reopened = p.decode(output)
        for key, value in changes.items():
            field = mapping[key]
            self.assertEqual(field.value(reopened.raw), value)
            self.assertEqual(output[field.offset:field.offset + field.size],
                             output[field.offset + p.ENTRY_SIZE:field.offset + p.ENTRY_SIZE + field.size])
        self.assertEqual(document.raw, raw)
        return reopened

    def test_procedural_raw_sizes_noops_both_replicas_and_immutable_snapshot(self):
        for size in (32768, 65536):
            raw = fixture(size)
            doc = p.decode(raw)
            self.assertEqual(p.serialize(doc, {}), raw)
            self.assertEqual(len(p.fields_for(doc)), 19)
            self.surgical(raw, {'gold': 5000, 'monster_0_stat_0': 999,
                                'monster_1_lifespan': 9999, 'player_name': 'TwelveChars!','monster_0_name': 'TwelveChars!'})
        for bad in (bytearray(raw), memoryview(raw), None):
            with self.assertRaises(SaveError):
                p.decode(bad)

