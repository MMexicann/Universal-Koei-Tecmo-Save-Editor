GAME = 'atelier_ryza_switch'


@lru_cache(maxsize=1)
def procedural_payload():
    empty = bytearray((index * 17 + 3) & 255 for index in range(66))
    struct.pack_into('<Hh', empty, 0, 65535, -1)
    pools = []
    for key, tag, label in parser.POOLS:
        capacity = {'basket': 200, 'important_basket': 100, 'container': 5000,
                    'important': 100, 'expendable': 50}[key]
        data = bytearray(bytes(empty) * capacity)
        if key in ('container', 'important'):
            struct.pack_into('<HhHH', data, 0, 100 if key == 'container' else 101, 42, 75, 0)
        pools.append(node(tag.decode(), struct.pack('>I', len(data)) + data))
    party = []
    for identity in range(9):
        body = bytearray((index * 31 + identity + 11) & 255 for index in range(942))
        struct.pack_into('>i', body, 0, identity if identity < 6 else -1)
        struct.pack_into('>I', body, 396, 66 * 8)
        for slot in range(8):
            record = bytearray(empty)
            if identity < 6:
                struct.pack_into('<H', record, 0, identity * 8 + slot)
            if identity == 0 and slot == 0:
                struct.pack_into('<hHH', record, 2, 473, 30, 0)
            body[400 + slot * 66:400 + (slot + 1) * 66] = record
        party.append(node('Party', bytes(body)))
    return (bytes.fromhex('013379c9') + bytes(28)
            + node('info', node('app_ver', struct.pack('>II', 1, 4)))
            + node('fieldmap', node('_I_HOUSE_KLAUDIA_01', b'1') + node('_T_BODEN', b'2'))
            + node('item', node('version', b'\0\1') + b''.join(pools))
            + node('party', node('version', b'\0\3') + struct.pack('>I', 9) + b''.join(party))
            + node('FieldMix', b'\0') + node('secret_base', node('opaque', b'keep me')))


def raw_for(payload=None, revision=4):
    if payload is None and revision == 4:
        return _default_raw()
    header = bytearray((index * 23 + 5) & 255 for index in range(256))
    header[:48] = b'\1' + bytes(39) + struct.pack('<II', 1, revision)
    return codec.encode_file(bytes(header), procedural_payload() if payload is None else payload,
                             0x12345678, b'\x13\x57\x9b')


@lru_cache(maxsize=1)
def _default_raw():
    # Cache immutable generated bytes, never mutable documents or validation.
    return raw_for(procedural_payload(), 4)


class RyzaSwitchTests(unittest.TestCase):
    def setUp(self):
        self.doc = parser.decode(raw_for(), GAME)

    def test_unchanged_and_every_quality_write_is_surgical(self):
        self.assertEqual(parser.serialize(self.doc, {}), self.doc.raw)
        self.assertEqual(len(parser.fields_for(self.doc)), 2)
        for field in parser.fields_for(self.doc):
            changes = parser.stage(self.doc, {}, field.id, 99)
            edited = parser.decode(parser.serialize(self.doc, changes), GAME)
            allowed = {field.offset, field.offset + 1}
            self.assertTrue(all(a == b or i in allowed for i, (a, b) in enumerate(zip(self.doc.payload, edited.payload))))
            self.assertEqual(edited.payload[field.offset + 2:field.offset + 4], self.doc.payload[field.offset + 2:field.offset + 4])
            self.assertEqual((edited.header, edited.seed, edited.footer, edited.trailer),
                             (self.doc.header, self.doc.seed, self.doc.footer, self.doc.trailer))
            self.assertEqual(parser.review(self.doc, changes)[0][2], 99)
            self.assertEqual(parser.stage(self.doc, changes, field.id, field.value(self.doc.payload)), {})
            self.assertFalse(field.maxable)
        self.assertEqual(parser.maximums(self.doc, {}), {})

    def test_foreign_revisions_corruption_and_framing(self):
        for revision in (0, 1, 2, 3, 5):
            with self.assertRaises(SaveError):
                parser.decode(raw_for(revision=revision), GAME)
        for offset in (0, 40, 44, 256, len(self.doc.raw) - 10):
            damaged = bytearray(self.doc.raw)
            damaged[offset] ^= 1
            with self.assertRaises(SaveError):
                parser.decode(damaged, GAME)
        for payload in (self.doc.payload[:-1], self.doc.payload + node('item', b'0'),
                        self.doc.payload.replace(b'_T_BODEN', b'_T_OTHER'),
                        self.doc.payload.replace(b'FieldMix', b'XieldMix')):
            with self.assertRaises(SaveError):
                parser.decode(raw_for(payload), GAME)
        for game in ('atelier_ryza', 'atelier_ryza2'):
            with self.assertRaises(SaveError):
                parser.decode(self.doc.raw, game)

    def test_nonzero_adjacent_synthesis_values_never_gain_a_quality_control(self):
        for field in parser.fields_for(self.doc):
            payload = bytearray(self.doc.payload)
            struct.pack_into('<H', payload, field.offset + 2, 37)
            doc = parser.decode(raw_for(bytes(payload)), GAME)
            self.assertNotIn(field.id, parser.field_map(doc))
            self.assertEqual(parser.serialize(doc, {}), doc.raw)
            with self.assertRaises(SaveError):
                parser.stage(doc, {}, field.id, 99)

    def test_invalid_values_unknown_fields_and_forged_document(self):
        field = parser.fields_for(self.doc)[0]
        for changes in ({field.id: True}, {field.id: 0}, {field.id: 101}, {'gold': 1}, None, []):
            with self.assertRaises(SaveError):
                parser.serialize(self.doc, changes)
        for forged in (replace(self.doc, seed=True), replace(self.doc, payload=bytearray(self.doc.payload)),
                       replace(self.doc, format=replace(self.doc.format))):
            with self.assertRaises(SaveError):
                parser.serialize(forged, {})

    def test_higher_values_reversible_and_zero_or_important_read_only(self):
        field = parser.fields_for(self.doc)[0]
        for value in (400, 1200, 65535, 0):
            payload = bytearray(self.doc.payload)
            struct.pack_into('<H', payload, field.offset, value)
            doc = parser.decode(raw_for(bytes(payload)), GAME)
            self.assertEqual(parser.serialize(doc, {}), doc.raw)
            self.assertEqual(parser.maximums(doc, {}), {})
            if value in (0, 65535):
                self.assertNotIn(field.id, parser.field_map(doc))
            else:
                changes = parser.stage(doc, {}, field.id, 99)
                self.assertEqual(parser.stage(doc, changes, field.id, value), {})
        self.assertNotIn('important_0_quality', parser.field_map(self.doc))

    def test_exact_equipment_aliases_are_read_only_and_ambiguous_ones_rejected(self):
        equipment = parser.field_map(self.doc)['character_0_0_quality']
        start = equipment.offset - 4
        payload = bytearray(self.doc.payload)
        payload[start + 66:start + 132] = payload[start:start + 66]
        doc = parser.decode(raw_for(bytes(payload)), GAME)
        self.assertNotIn('character_0_0_quality', parser.field_map(doc))
        self.assertNotIn('character_0_1_quality', parser.field_map(doc))
        self.assertEqual(parser.serialize(doc, {}), doc.raw)
        payload[start + 66 + 20] ^= 1
        with self.assertRaises(SaveError):
            parser.decode(raw_for(bytes(payload)), GAME)
        payload = bytearray(self.doc.payload)
        field = parser.fields_for(self.doc)[0]
        start = field.offset - 4
        payload[start + 66:start + 132] = payload[start:start + 66]
        with self.assertRaises(SaveError):
            parser.decode(raw_for(bytes(payload)), GAME)

    def test_safe_copy_backup_restore_source_changed_and_destination_guards(self):
        with tempfile.TemporaryDirectory() as folder:
            folder = Path(folder)
            source = folder / 'copy.dat'
            source.write_bytes(self.doc.raw)
            doc = parser.read_save(source, GAME)
            field = parser.fields_for(doc)[0]
            target = folder / 'edited.dat'
            changes = parser.stage(doc, {}, field.id, 99)
            edited = parser.save_as(doc, changes, target)
            self.assertEqual(field.value(edited.payload), 99)
            self.assertEqual(source.read_bytes(), doc.raw)
            backup = parser.backup(doc)
            restored = parser.restore(backup, folder / 'restored.dat', GAME)
            self.assertEqual(Path(restored).read_bytes(), doc.raw)
            for destination in (source, target):
                with self.assertRaises(FileExistsError):
                    parser.save_as(doc, changes, destination)
            source.write_bytes(b'changed')
            with self.assertRaises(SaveError):
                parser.save_as(doc, changes, folder / 'changed.dat')

    @unittest.skipUnless(os.environ.get('RYZA1_SWITCH_NATIVE_DIR'), 'Private native Ryza Switch exports not selected')
    def test_native_main_game_slots_integrity_and_edit_preservation(self):
        files = sorted(Path(os.environ['RYZA1_SWITCH_NATIVE_DIR']).rglob('data.dat'))
        self.assertGreaterEqual(len(files), 2)
        for source in files:
            doc = parser.decode(source.read_bytes(), GAME)
            self.assertEqual(parser.serialize(doc, {}), doc.raw)
            fields = parser.fields_for(doc)
            self.assertGreater(len(fields), 100)
            changes = {field.id: 99 for field in fields}
            edited = parser.decode(parser.serialize(doc, changes), GAME)
            allowed = {field.offset + i for field in fields for i in range(2)}
            self.assertTrue(all(a == b or i in allowed for i, (a, b) in enumerate(zip(doc.payload, edited.payload))))
            self.assertEqual((doc.header, doc.seed, doc.footer, doc.trailer),
                             (edited.header, edited.seed, edited.footer, edited.trailer))
            with tempfile.TemporaryDirectory() as folder:
                copied = Path(folder) / 'copy.dat'
                copied.write_bytes(doc.raw)
                copied_doc = parser.read_save(copied, GAME)
                parser.save_as(copied_doc, changes, Path(folder) / 'edited.dat')
                backup = parser.backup(copied_doc)
                parser.restore(backup, Path(folder) / 'restored.dat', GAME)
                self.assertEqual((Path(folder) / 'restored.dat').read_bytes(), doc.raw)


@unittest.skipUnless(os.name == 'nt' or os.environ.get('DISPLAY'), 'Graphical display required')
class RyzaSwitchGuiTests(unittest.TestCase):
    def test_open_inspect_edit_undo_review_save_and_restore(self):
        import tkinter as tk
        from koei_editor.games.ryza.editor1switch import Editor
        root = tk.Tk()
        root.withdraw()
        try:
            with tempfile.TemporaryDirectory() as folder:
                folder = Path(folder)
                source, target, restored = (folder / name for name in ('source.dat', 'edited.dat', 'restored.dat'))
                native = os.environ.get('RYZA1_SWITCH_NATIVE_DIR')
                raw = next(Path(native).rglob('data.dat')).read_bytes() if native else raw_for()
                source.write_bytes(raw)
                editor = Editor(root)
                with patch('koei_editor.shared.verified_gui.filedialog.askopenfilename', return_value=str(source)), \
                     patch('koei_editor.shared.verified_gui.messagebox.showerror') as errors:
                    editor.open()
                    errors.assert_not_called()
                field = parser.fields_for(editor.document)[0]
                tables = editor.presentation.inspection_tables(editor.document)
                self.assertTrue(tables[0].rows)
                editor.fields.selection_set(field.id)
                editor.value.set('99')
                editor.apply_selected()
                self.assertEqual(editor.changes, {field.id: 99})
                editor.undo()
                self.assertEqual(editor.changes, {})
                editor.value.set('99')
                editor.apply_selected()
                editor.review()
                next(widget for widget in root.winfo_children() if isinstance(widget, tk.Toplevel)).destroy()
                editor.apply_theme('Dark')
                with patch('koei_editor.shared.verified_gui.filedialog.asksaveasfilename', return_value=str(target)), \
                     patch('koei_editor.shared.verified_gui.messagebox.showerror') as errors:
                    editor.save_as()
                    errors.assert_not_called()
                edited = parser.read_save(target, GAME)
                self.assertEqual(field.value(edited.payload), 99)
                self.assertEqual(source.read_bytes(), raw)
                backup = next((folder / 'WarriorsEditorBackups').glob('*.dat'))
                with patch('koei_editor.shared.verified_gui.filedialog.askopenfilename', return_value=str(backup)), \
                     patch('koei_editor.shared.verified_gui.filedialog.asksaveasfilename', return_value=str(restored)), \
                     patch('koei_editor.shared.verified_gui.messagebox.showerror') as errors:
                    editor.restore()
                    errors.assert_not_called()
                self.assertEqual(restored.read_bytes(), raw)
        finally:
            root.destroy()
