import test from "node:test";
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { validateMod } from "../src/sandbox-core.mjs";
import { clearStagedProfile, loadStagedMods, removeStagedMod, saveStagedMod } from "../src/workspace-store.mjs";

const GAME = "wolong";

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

function stagedMod({ storageKey, manifest, bytes, sha }) {
  const [file] = manifest.files;
  return {
    storageKey,
    manifest,
    gameId: manifest.game,
    gameVersion: manifest.gameVersion,
    id: manifest.id,
    name: manifest.name,
    version: manifest.version,
    author: "Test fixture",
    description: "Inert generated bytes",
    valid: true,
    validationErrors: [],
    files: [{ source: file.source, target: file.target, sha256: sha }],
    payloads: new Map([[file.source, new Blob([bytes])]]),
  };
}

test("removing a memory-only staged mod reports success and removes its fallback record", async () => {
  const storageKey = `workspaces/${GAME}/build-1/memory-remove-${Date.now()}-${Math.random().toString(16).slice(2)}`;
  const bytes = "inert payload";
  const digest = sha256(bytes);
  const manifest = {
    schemaVersion: 1,
    id: "memory-remove-test",
    name: "Memory remove test",
    version: "1.0",
    game: GAME,
    gameVersion: "build-1",
    files: [{ source: "data/payload.bin", target: "mods/payload.bin", sha256: digest }],
  };
  await saveStagedMod(stagedMod({ storageKey, manifest, bytes, sha: digest }));
  assert.ok((await loadStagedMods()).some((item) => item.storageKey === storageKey));

  const removed = await removeStagedMod(storageKey);
  assert.equal(removed, true);
  assert.equal((await loadStagedMods()).some((item) => item.storageKey === storageKey), false);
});

test("restored manifest digests are rechecked against payload bytes instead of stored metadata", async () => {
  const storageKey = `workspaces/${GAME}/build-1/restore-hash-${Date.now()}-${Math.random().toString(16).slice(2)}`;
  const originalBytes = "approved payload";
  const changedBytes = "tampered payload";
  const declaredDigest = sha256(originalBytes);
  const manifest = {
    schemaVersion: 1,
    id: "restore-hash-test",
    name: "Restore hash test",
    version: "1.0",
    game: GAME,
    gameVersion: "build-1",
    files: [{ source: "data/payload.bin", target: "mods/payload.bin", sha256: declaredDigest }],
  };

  // Simulate stale/tampered persisted bytes while metadata still claims the import-time digest.
  await saveStagedMod(stagedMod({ storageKey, manifest, bytes: changedBytes, sha: declaredDigest }));
  const restored = (await loadStagedMods()).find((item) => item.storageKey === storageKey);
  assert.ok(restored);

  assert.equal(restored.inventory[0].sha256, sha256(changedBytes), "restore must recalculate the digest from the stored bytes");
  assert.notEqual(restored.inventory[0].sha256, declaredDigest, "restore must not trust the digest stored beside the payload");
  const validation = validateMod(restored.manifest, GAME, restored.inventory, "build-1");
  assert.equal(validation.ok, false, "a matching stored digest must not bless changed restored bytes");
  assert.ok(validation.errors.some((error) => ["sha256_mismatch", "unverified_sha256"].includes(error.code)));
});

test("restored Workshop replacement digests are rechecked from native replacement entries", async () => {
  const storageKey = `workspaces/${GAME}/1.5.0/workshop-restore-${Date.now()}-${Math.random().toString(16).slice(2)}`;
  const originalBytes = "approved Workshop replacement";
  const changedBytes = "tampered Workshop replacement";
  const declaredDigest = sha256(originalBytes);
  const manifest = {
    schema_version: 1,
    mod_id: "workshop-restore-test",
    name: "Workshop restore test",
    version: "1.0.0",
    author: "Test author",
    description: "",
    game_id: GAME,
    game_version: "1.5.0",
    platform: "Windows PC",
    license: "MIT",
    dependencies: [],
    replacements: [{ source_path: "replacements/payload.bin", target_path: "mods/payload.bin", sha256: declaredDigest, license: "MIT", attribution: "", rights_status: "creator-owned" }],
  };
  const validated = validateMod(manifest, GAME, [{ path: "replacements/payload.bin", size: originalBytes.length, sha256: declaredDigest }], "1.5.0");
  assert.equal(validated.ok, true);
  await saveStagedMod({
    storageKey,
    manifest,
    gameId: GAME,
    gameVersion: "1.5.0",
    id: validated.mod.id,
    name: validated.mod.name,
    version: validated.mod.version,
    author: validated.mod.author,
    description: validated.mod.description,
    valid: true,
    validationErrors: [],
    files: validated.mod.files,
    payloads: new Map([["replacements/payload.bin", new Blob([changedBytes])]]),
  });

  const restored = (await loadStagedMods()).find((item) => item.storageKey === storageKey);
  assert.ok(restored);
  assert.equal(restored.inventory[0].sha256, sha256(changedBytes));
  const validation = validateMod(restored.manifest, GAME, restored.inventory, "1.5.0");
  assert.equal(validation.ok, false);
  assert.ok(validation.errors.some((error) => error.code === "sha256_mismatch"));
  await removeStagedMod(storageKey);
});

test("clearing a memory-only game profile preserves other stored profiles", async () => {
  const suffix = `${Date.now()}-${Math.random().toString(16).slice(2)}`;
  const buildOne = {
    schemaVersion: 1,
    id: `profile-one-${suffix}`,
    name: "Profile one",
    version: "1.0",
    game: GAME,
    gameVersion: "build-1",
    files: [{ source: "data/one.bin", target: "mods/one.bin" }],
  };
  const buildTwo = {
    schemaVersion: 1,
    id: `profile-two-${suffix}`,
    name: "Profile two",
    version: "1.0",
    game: GAME,
    gameVersion: "build-2",
    files: [{ source: "data/two.bin", target: "mods/two.bin" }],
  };
  const firstKey = `workspaces/${GAME}/build-1/${buildOne.id}`;
  const secondKey = `workspaces/${GAME}/build-2/${buildTwo.id}`;
  await saveStagedMod(stagedMod({ storageKey: firstKey, manifest: buildOne, bytes: "one", sha: null }));
  await saveStagedMod(stagedMod({ storageKey: secondKey, manifest: buildTwo, bytes: "two", sha: null }));

  assert.equal(await clearStagedProfile(GAME, "build-1"), true);
  const remaining = await loadStagedMods();
  assert.equal(remaining.some((item) => item.storageKey === firstKey), false);
  assert.equal(remaining.some((item) => item.storageKey === secondKey), true);
  await removeStagedMod(secondKey);
});

test("same game and mod ID under different exact builds remain independently stored and removable", async () => {
  const suffix = `${Date.now()}-${Math.random().toString(16).slice(2)}`;
  const modId = `same-mod-${suffix}`;
  const makeManifest = (gameVersion) => ({
    schemaVersion: 1,
    id: modId,
    name: `Same mod ${gameVersion}`,
    version: "1.0",
    game: GAME,
    gameVersion,
    files: [{ source: "data/payload.bin", target: "mods/payload.bin" }],
  });
  const firstVersion = "build-1.0";
  const secondVersion = "build-2.0";
  const firstKey = `workspaces/${GAME}/${encodeURIComponent(firstVersion)}/${modId}`;
  const secondKey = `workspaces/${GAME}/${encodeURIComponent(secondVersion)}/${modId}`;
  await saveStagedMod(stagedMod({ storageKey: firstKey, manifest: makeManifest(firstVersion), bytes: "payload for build one", sha: null }));
  await saveStagedMod(stagedMod({ storageKey: secondKey, manifest: makeManifest(secondVersion), bytes: "payload for build two", sha: null }));

  const initial = (await loadStagedMods()).filter((item) => item.id === modId);
  assert.equal(initial.length, 2);
  assert.notEqual(initial[0].storageKey, initial[1].storageKey);
  const first = initial.find((item) => item.gameVersion === firstVersion);
  const second = initial.find((item) => item.gameVersion === secondVersion);
  assert.equal(await first.payloads.get("data/payload.bin").text(), "payload for build one");
  assert.equal(await second.payloads.get("data/payload.bin").text(), "payload for build two");

  assert.equal(await removeStagedMod(firstKey), true);
  const remaining = (await loadStagedMods()).filter((item) => item.id === modId);
  assert.equal(remaining.length, 1);
  assert.equal(remaining[0].gameVersion, secondVersion);
  assert.equal(await remaining[0].payloads.get("data/payload.bin").text(), "payload for build two");
  await removeStagedMod(secondKey);
});
